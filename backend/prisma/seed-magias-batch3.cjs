async function seed() {
  let upserted = 0;

  for (const magia of magias) {
    await prisma.magias_tresdet.upsert({
      where: { nome: magia.nome },
      update: {
        descricao: magia.descricao,
        escola: magia.escola,
        custo_pm: magia.custo_pm,
        alcance: magia.alcance,
        duracao: magia.duracao,
        tipo: magia.tipo,
        exigencias: magia.exigencias,
        focus_requisito: magia.focus_requisito,
        nivel_minimo: magia.nivel_minimo,
      },
      create: magia,
    });
    upserted++;
  }

  console.log(`Batch 3: ${upserted} magias upserted.`);

  const total = await prisma.magias_tresdet.count();
  console.log(`Total magias_tresdet in database: ${total}`);
}

seed()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
