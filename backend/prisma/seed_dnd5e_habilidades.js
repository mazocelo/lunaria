function buildData(spell) {
  return {
    nome: spell.nome,
    descricao: spell.descricao,
    custo_mana: spell.custo_mana,
    dano_base: spell.dano_base || null,
    tipo: spell.tipo,
    escola_magia: spell.escola_magia || null,
    nivel_requerido: spell.nivel_requerido,
    alcance: spell.alcance || 'medio',
    alvo: spell.alvo,
    tempo_conjuracao: spell.tempo_conjuracao || 'acao',
    usa_concentracao: spell.usa_concentracao ?? false,
    categoria: spell.categoria || 'magia_ofensiva',
    saving_throw: spell.saving_throw || null,
    efeito: spell.efeito || null,
    componente_material: spell.componente_material || null,
    cooldown_turnos: 0,
  };
}

async function main() {
  console.log(`Inserindo ${spells.length} magias D&D 5e...`);

  let inseridas = 0;
  let erros = 0;

  for (const spell of spells) {
    try {
      const data = buildData(spell);
      await prisma.habilidades_magias.upsert({
        where: { nome_sistema: { nome: spell.nome, sistema: 'dnd5e' } },
        create: { ...data, sistema: 'dnd5e' },
        update: data,
      });
      inseridas++;
    } catch (err) {
      console.error(`Erro em "${spell.nome}":`, err.message);
      erros++;
    }
  }

  console.log(`Magias D&D 5e: ${inseridas} inseridas/atualizadas, ${erros} com erro.`);

  const total = await prisma.habilidades_magias.count({ where: { sistema: 'dnd5e' } });
  console.log(`Total magias D&D 5e no banco: ${total}`);
}

main()
  .catch(e => { console.error(e); process.exit(1); })
  .finally(() => prisma.$disconnect());
